"""
PDKind vs K-Induction Evaluation Script
Compares pono's built-in k-induction (-e ind) against our PDKind engine (-e pdkind)
across a suite of BTOR2 benchmarks.

Usage:
    cd pono-src
    python3 ../evaluation/evaluate.py

Output: a Markdown table + per-benchmark verbose logs
"""

import subprocess
import time
import re
import os
import sys

# --------------------------------------------------------------------------- #
# Configuration
# --------------------------------------------------------------------------- #

PONO    = "./build/pono"          # path to binary (run from pono-src/)
BOUND   = 20                      # max unrolling depth for both engines
TIMEOUT = 60                      # seconds per run

BENCHMARKS = [
    # (display_name,           btor2_path,                        expected_verdict)
    ("uv_example",       "samples/uv_example.btor2",         "SAFE"),
    ("uvw_example",      "samples/uvw_example.btor2",         "SAFE"),
    ("xp2",              "samples/xp2.btor2",                 "SAFE"),
    ("counter_true",     "samples/counter-true.btor",         "SAFE"),
    ("counter_false",    "samples/counter.btor",              "UNSAFE"),
    ("neg_rst_test",     "samples/neg_rst_test.btor2",        "UNSAFE"),
    ("state2input",      "samples/state2input.btor",          "UNSAFE"),
]

# --------------------------------------------------------------------------- #
# Runner
# --------------------------------------------------------------------------- #

def run_engine(engine, benchmark_path, verbosity=2):
    """Run pono with the given engine and return (verdict, elapsed_sec, lemma_count)."""
    cmd = [PONO, "-e", engine, "-k", str(BOUND), "-v", str(verbosity),
           benchmark_path]
    start = time.perf_counter()
    try:
        proc = subprocess.run(
            cmd, capture_output=True, text=True, timeout=TIMEOUT,
            cwd=os.path.dirname(os.path.abspath(__file__)) + "/../pono-src"
        )
        elapsed = time.perf_counter() - start
        out = proc.stdout + proc.stderr
    except subprocess.TimeoutExpired:
        return "TIMEOUT", TIMEOUT, 0, ""

    elapsed = time.perf_counter() - start

    # Parse verdict from first meaningful output line
    if "unsat" in out.lower():
        verdict = "SAFE"
    elif "sat" in out.lower() and "unsat" not in out.lower():
        verdict = "UNSAFE"
    elif "unknown" in out.lower():
        verdict = "UNKNOWN"
    else:
        verdict = "ERROR"

    # Count non-trivial lemmas generated (PDKind-specific)
    lemma_lines  = re.findall(r"new lemma at k=(\d+): (.+)", out)
    useful_lemmas = [(k, l) for k, l in lemma_lines if l.strip() != "true"]
    lemma_count  = len(lemma_lines)
    useful_count = len(useful_lemmas)

    return verdict, elapsed, lemma_count, useful_count, out


# --------------------------------------------------------------------------- #
# Main
# --------------------------------------------------------------------------- #

def main():
    print(f"\n{'='*90}")
    print(f"  PDKind vs K-Induction Evaluation   (bound={BOUND}, timeout={TIMEOUT}s)")
    print(f"{'='*90}\n")

    # Header
    col = [22, 10, 9, 10, 9, 8, 8, 12]
    hdr = ["Benchmark", "Expected", "KInd", "KInd(s)", "PDKind", "PDK(s)",
           "Lemmas", "Useful Lemmas"]
    print("  " + "  ".join(h.ljust(col[i]) for i, h in enumerate(hdr)))
    print("  " + "-"*88)

    results = []

    for name, path, expected in BENCHMARKS:
        if not os.path.exists(os.path.join("pono-src", path)):
            print(f"  {name:<22} FILE NOT FOUND — skipping")
            continue

        ki_v,  ki_t,  _,         _,          _ = run_engine("ind",    path)
        pk_v,  pk_t,  pk_total,  pk_useful,  pk_out = run_engine("pdkind", path)

        # Correctness flag
        agree  = "✓" if ki_v == pk_v else ("?" if "UNKNOWN" in (ki_v, pk_v) else "✗")
        pk_wins = ki_v == "UNKNOWN" and pk_v != "UNKNOWN"

        row = [name, expected, ki_v, f"{ki_t:.2f}s", pk_v, f"{pk_t:.2f}s",
               str(pk_total), str(pk_useful)]
        marker = "  ← PDKind wins!" if pk_wins else ""
        print("  " + "  ".join(str(row[i]).ljust(col[i]) for i in range(len(row))) + marker)

        results.append((name, expected, ki_v, ki_t, pk_v, pk_t, pk_total, pk_useful, pk_out))

    print()
    print("  Lemmas = total lemmas generated by PDKind")
    print("  Useful = lemmas that are not trivially 'true' (actually constrain the search)")
    print()

    # ---------- Correctness summary ----------------------------------------- #
    print(f"{'='*90}")
    print("  CORRECTNESS CHECK")
    print(f"{'='*90}")
    definitive = [(n, e, ki, pk) for n, e, ki, _, pk, *_ in results
                  if ki not in ("UNKNOWN", "TIMEOUT", "ERROR")
                  and pk not in ("UNKNOWN", "TIMEOUT", "ERROR")]
    agree_count   = sum(1 for _, _, ki, pk in definitive if ki == pk)
    disagree_list = [(n, ki, pk) for n, _, ki, pk in definitive if ki != pk]

    print(f"  Benchmarks with definitive answer from both: {len(definitive)}")
    print(f"  Agreement:                                   {agree_count}/{len(definitive)}")
    if disagree_list:
        print("  DISAGREEMENTS (bug — investigate):")
        for n, ki, pk in disagree_list:
            print(f"    {n}: ind={ki}, pdkind={pk}")
    else:
        print("  No disagreements — PDKind is sound on these benchmarks ✓")

    # ---------- PDKind wins ------------------------------------------------- #
    print()
    print(f"{'='*90}")
    print("  WHERE PDKIND HELPS")
    print(f"{'='*90}")
    wins = [(n, e, ki, pk, pt) for n, e, ki, _, pk, pt, *_ in results
            if ki == "UNKNOWN" and pk not in ("UNKNOWN", "TIMEOUT", "ERROR")]
    if wins:
        for n, e, ki, pk, pt in wins:
            print(f"  {n}: k-induction=UNKNOWN, PDKind={pk} in {pt:.2f}s — "
                  f"lemmas broke the deadlock")
    else:
        print("  No benchmarks where PDKind proved/refuted but k-induction could not.")
        print("  (This reflects a current implementation limitation — see notes below.)")

    # ---------- Lemma deep-dive --------------------------------------------- #
    print()
    print(f"{'='*90}")
    print("  LEMMA ANALYSIS (PDKind verbose output)")
    print(f"{'='*90}")
    for name, _, _, _, _, _, total, useful, out in results:
        lemma_lines = re.findall(r"(PDKind: (?:new lemma|literal_drop).+)", out)
        proof_line  = re.findall(r"(PDKind: property proved.+)", out)
        if lemma_lines or proof_line:
            print(f"\n  [{name}]")
            for l in lemma_lines[:6]:   # cap at 6 lines per benchmark
                print(f"    {l}")
            for l in proof_line:
                print(f"    {l}")
            if total > 0 and useful == 0:
                print(f"    NOTE: All {total} lemma(s) were trivially 'true' — "
                      "literal_drop found no essential literals (no constraint added).")

    # ---------- Notes on limitations ---------------------------------------- #
    print()
    print(f"{'='*90}")
    print("  KNOWN LIMITATIONS OF CURRENT IMPLEMENTATION")
    print(f"{'='*90}")
    print("""
  1. TRIVIAL LEMMAS: When literal_drop produces 'true' (all literals droppable),
     the lemma adds no information to the solver. This happens when the
     bad state is reachable from any pre-state in one step, meaning
     no single-literal constraint can block it. The full PDKind algorithm
     handles this via a 'prophecy' mechanism not yet implemented.

  2. UNTIMED LEMMA ASSERTION: Lemmas are asserted as untimed formulas over
     the original state variables. The timed unrolling uses renamed variables
     (v@0, v@1, ...), so untimed lemmas do not directly constrain timed states.
     A complete implementation would unroll each lemma at every depth.

  3. INCOMPLETE PROOF ON uvw/xp2: Due to limitation (1), PDKind cannot prove
     uvw_example or xp2 within k=20, while standard k-induction proves uvw_example.
     This is an implementation gap, not a fundamental algorithmic failure.
  """)

if __name__ == "__main__":
    # Run from the repo root
    os.chdir(os.path.dirname(os.path.abspath(__file__)) + "/..")
    main()
